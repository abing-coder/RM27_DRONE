#!/usr/bin/env python3
"""Build the 2027 STEP field from an audited CAD-to-map layout.

STEP conversion is offline. Gazebo loads only the generated DAE/STL/SDF files.
The existing legacy world and its textures are never regenerated by this tool.
"""
import argparse
import hashlib
import json
import math
import re
from pathlib import Path
import subprocess
import sys

import numpy as np
import yaml

from gen_field import PKG, mat, ARMOR_CLASSES, ARMOR_PATTERNS, MODEL_DIR
from step_mesh import transform_points, write_collada, write_stl, simplify_by_color


class TerrainRow(list):
    pass


class MapDumper(getattr(yaml, 'CSafeDumper', yaml.SafeDumper)):
    pass


MapDumper.add_representer(TerrainRow, lambda dumper, row: dumper.represent_sequence(
    'tag:yaml.org,2002:seq', row, flow_style=True))


def pose(x, y, z, roll=0., pitch=0., yaw=0.):
    # Keep CAD mounting rotations/positions at the same precision as map anchors.
    return '<pose>' + ' '.join(f'{v:.9f}' for v in (x, y, z, roll, pitch, yaw)) + '</pose>'


def sha256(path):
    digest = hashlib.sha256()
    with Path(path).open('rb') as stream:
        for block in iter(lambda: stream.read(8 * 1024 * 1024), b''):
            digest.update(block)
    return digest.hexdigest()


def read_cache(source, directory):
    """Never reuse geometry from a different STEP, or an interrupted extraction."""
    directory = Path(directory)
    metadata_path = directory / 'metadata.json'
    digest = sha256(source)
    try:
        metadata = json.loads(metadata_path.read_text()) if metadata_path.exists() else {}
    except json.JSONDecodeError:
        metadata = {}  # An interrupted metadata write is not a reusable cache.
    if metadata.get('source_sha256') != digest or not metadata.get('complete'):
        subprocess.run([sys.executable, str(Path(__file__).with_name('step_xde.py')),
                        str(source), str(directory)], check=True)
        metadata = json.loads(metadata_path.read_text())
    if metadata['source_sha256'] != digest or metadata['unit'] != 'mm':
        raise ValueError('Unexpected STEP cache source or unit')
    return metadata


def rotation_pose(matrix):
    rotation = matrix[:3, :3]
    if not np.allclose(rotation.T @ rotation, np.eye(3), atol=1e-5) or np.linalg.det(rotation) < .999:
        raise ValueError('CAD instance has a non-rigid transform')
    pitch = math.asin(np.clip(-rotation[2, 0], -1, 1))
    if abs(math.cos(pitch)) > 1e-7:
        roll = math.atan2(rotation[2, 1], rotation[2, 2])
        yaw = math.atan2(rotation[1, 0], rotation[0, 0])
    else:
        roll = 0.0
        yaw = math.atan2(-rotation[0, 1], rotation[1, 1])
    return (*matrix[:3, 3], roll, pitch, yaw)


def armor_data(layout, cad_to_map):
    targets, models = [], []
    counts = {}
    for armor in layout['armor_mounts']:
        team, kind, armor_type = armor['team'], armor['kind'], armor['armor_type']
        key = f'{team}_{kind}'
        index = counts.get(key, 0)
        counts[key] = index + 1
        normal = np.asarray(armor['normal_cad'], dtype=float)
        normal = cad_to_map[:3, :3] @ normal
        normal /= np.linalg.norm(normal)
        center = transform_points([armor['center_cad_mm']], cad_to_map)[0]
        up = cad_to_map[:3, :3] @ np.asarray(armor['up_cad'], dtype=float)
        up -= normal * (normal @ up)
        up /= np.linalg.norm(up)
        width_axis = np.cross(up, normal)
        rotation = np.column_stack((normal, width_axis, up))
        matrix = np.eye(4)
        matrix[:3, :3], matrix[:3, 3] = rotation, center
        bar_distance = float(layout['vision']['small_armor_bar_distance'])
        bar_height = float(layout['vision']['light_bar_length'])
        surface_offset = .0032
        name = f'{key}_armor_{index}'
        face_material, face_texture, _ = ARMOR_PATTERNS[kind]
        from PIL import Image
        with Image.open(Path(MODEL_DIR) / 'materials' / 'textures' / face_texture) as icon:
            aspect = icon.width / icon.height
        height = min(.100, .115 / aspect)
        width = height * aspect
        lamp_material = 'RM/RedLightBar' if team == 'red' else 'RM/BlueLightBar'
        # CAD already contains the housing. Add only its sticker/emitting surfaces
        # and a 1 mm contact face; do not stack a second 12 mm armour body on it.
        visuals = (f'<visual name="sticker"><pose>.0023 0 0 0 0 0</pose><geometry><mesh>'
                   f'<uri>model://rm_field/meshes/armor_face.dae</uri><scale>1 {width:.7f} {height:.7f}</scale>'
                   f'</mesh></geometry>{mat(face_material)}</visual>')
        for side in (-1, 1):
            visuals += (f'<visual name="light_{side}"><pose>.0028 {side * bar_distance / 2:.7f} 0 0 0 0</pose>'
                        f'<geometry><box><size>.0008 .012 {bar_height:.7f}</size></box></geometry>'
                        f'{mat(lamp_material)}</visual>')
        models.append(f'<model name="{name}_model"><static>true</static><link name="{name}">'
                      f'{pose(*rotation_pose(matrix))}<collision name="{name}_collision">'
                      '<pose>.0027 0 0 0 0 0</pose><geometry><box><size>.001 .1408 .125</size></box></geometry>'
                      f'</collision>{visuals}<sensor name="{name}_contact" type="contact">'
                      f'<always_on>true</always_on><update_rate>500</update_rate><contact><collision>{name}_collision</collision></contact>'
                      f'<plugin name="{name}_impact" filename="libarmor_impact_plugin.so"><armor_name>{name}</armor_name>'
                      f'<link_name>{name}</link_name><striker_entity>rm_drone</striker_entity>'
                      '<force_threshold>2.0</force_threshold></plugin></sensor></link></model>')
        position = center + normal * surface_offset
        corners = [(center + rotation @ np.array([surface_offset, y, z])).tolist()
                   for y, z in [(-bar_distance / 2, bar_height / 2), (-bar_distance / 2, -bar_height / 2),
                                (bar_distance / 2, -bar_height / 2), (bar_distance / 2, bar_height / 2)]]
        targets.append(dict(name=name, team=team, kind=kind, armor_type=armor_type,
                            class_id=ARMOR_CLASSES[(team, kind)], pattern=kind,
                            position=position.tolist(), normal=normal.tolist(),
                            normal_yaw=math.atan2(normal[1], normal[0]), spin_speed=0.0,
                            light_bar_corners=corners,
                            cad_source=armor['source']))
    if counts != layout['expected_armors']:
        raise ValueError(f'Armor audit failed: {counts} != {layout["expected_armors"]}')
    return targets, models


def team_mesh(path, team):
    """CAD repeats some red display parts on both sides; set their team colours."""
    target = path.with_name(path.stem + '_' + team + path.suffix)
    color = '.85 .01 .01 1' if team == 'red' else '.01 .03 .85 1'
    changed = False
    def replace(match):
        nonlocal changed
        values = [float(x) for x in match[2].split()]
        r, g, b = values[:3]
        if (r > .6 and g < .2 and b < .2) or (b > .6 and r < .2 and g < .2):
            changed = True
            return match[1] + color + match[3]
        return match[0]
    text = re.sub(r'(<(?:ambient|diffuse)><color>)([^<]+)(</color>)', replace, path.read_text())
    if changed:
        target.write_text(text)
        return target
    return path


def geometry_assets(metadata, cache, model_dir, cad_to_map, team_instances=None):
    meshes = model_dir / 'meshes'
    meshes.mkdir(parents=True, exist_ok=True)
    marker = model_dir / 'cad_mesh_manifest.json'
    fingerprint = dict(source_sha256=metadata['source_sha256'], mesh_version=1)
    reuse = marker.exists() and json.loads(marker.read_text()) == fingerprint
    definitions = {}
    for definition in metadata['definitions']:
        if not definition['triangles']:
            continue
        data = np.load(cache / definition['file'])
        name = definition['entry'].replace(':', '_')
        if not (reuse and (meshes / (name + '.dae')).exists() and (meshes / (name + '.stl')).exists()):
            vertices, faces, colors = simplify_by_color(data['vertices'], data['triangles'], data['colors'])
            vertices = vertices.astype(np.float64) * .001
            write_collada(meshes / (name + '.dae'), vertices, faces, colors)
            write_stl(meshes / (name + '.stl'), vertices, faces)
            print(f'CAD mesh {name}: {definition["triangles"]} -> {len(faces)} triangles', flush=True)
        definitions[definition['entry']] = (name, data['vertices'], data['triangles'])
    links, instances = [], []
    for index, instance in enumerate(metadata['instances']):
        if instance['entry'] not in definitions:
            continue
        name, vertices, faces = definitions[instance['entry']]
        native = np.asarray(instance['transform'], dtype=float)
        world = cad_to_map @ native @ np.diag([1000., 1000., 1000., 1.])
        uri = f'model://rmuc2027_official/meshes/{name}'
        team = (team_instances or {}).get(index)
        visual_uri = uri + '.dae'
        if team:
            variant = team_mesh(meshes / (name + '.dae'), team)
            visual_uri = 'model://rmuc2027_official/meshes/' + variant.name
        links.append(f'<link name="cad_{index}">{pose(*rotation_pose(world))}'
                     f'<visual name="geometry"><geometry><mesh><uri>{visual_uri}</uri></mesh></geometry></visual>'
                     f'<collision name="geometry"><geometry><mesh><uri>{uri}.stl</uri></mesh></geometry>'
                     '<surface><friction><ode><mu>0.8</mu><mu2>0.8</mu2></ode></friction></surface>'
                     '</collision></link>')
        points = transform_points(vertices, cad_to_map @ native)
        instances.append(dict(index=index, source=instance, vertices=points, faces=faces))
    sdf = '<sdf version="1.6"><model name="rmuc2027_official"><static>true</static>' + ''.join(links) + '</model></sdf>'
    (model_dir / 'model.sdf').write_text('<?xml version="1.0"?>\n' + sdf)
    (model_dir / 'model.config').write_text(
        '<?xml version="1.0"?><model><name>RMUC 2027 STEP V1.0.0</name><version>1.0</version>'
        '<sdf version="1.6">model.sdf</sdf><description>User-provided 2027 CAD, colours preserved; metres.</description></model>')
    marker.write_text(json.dumps(fingerprint, indent=2))
    return instances


def energy_asset(metadata, cache):
    definition = metadata['definitions'][0]
    data = np.load(cache / definition['file'])
    vertices = data['vertices'].astype(float) * .001
    vertices = vertices @ np.array([[1, 0, 0], [0, 0, -1], [0, 1, 0]]).T
    directory = Path(PKG) / 'models' / 'rmuc2027_energy_unit'
    (directory / 'meshes').mkdir(parents=True, exist_ok=True)
    write_collada(directory / 'meshes' / 'energy_unit.dae', vertices, data['triangles'], data['colors'])
    write_stl(directory / 'meshes' / 'energy_unit.stl', vertices, data['triangles'])
    (directory / 'model.config').write_text(
        '<?xml version="1.0"?><model><name>RMUC 2027 能量单元</name><version>1.0</version>'
        '<sdf version="1.6">model.sdf</sdf><description>用户提供的能量单元 STEP；米，Z-up。</description></model>')
    (directory / 'model.sdf').write_text(
        '<?xml version="1.0"?><sdf version="1.6"><model name="rmuc2027_energy_unit">'
        '<static>false</static><link name="body"><inertial><pose>0 0 0.075 0 0 0</pose>'
        '<mass>0.4</mass><inertia><ixx>0.001</ixx><iyy>0.001</iyy><izz>0.0005</izz>'
        '<ixy>0</ixy><ixz>0</ixz><iyz>0</iyz></inertia></inertial>'
        '<visual name="cad"><geometry><mesh>'
        '<uri>model://rmuc2027_energy_unit/meshes/energy_unit.dae</uri></mesh></geometry></visual>'
        '<collision name="body"><pose>0 0 0.075 0 0 0</pose><geometry><cylinder>'
        '<radius>0.0515</radius><length>0.15</length></cylinder></geometry></collision>'
        '</link></model></sdf>')


def surface_obstacles(instances, layout):
    """Conservative spatial boxes from CAD surface patches, rather than old scenery."""
    resolution = float(layout.get('collision_map_resolution', .15))
    field = layout['field']
    lower_world = np.array([-field['length'] / 2, -field['width'] / 2, 0.])
    upper_world = np.array([field['length'] / 2, field['width'] / 2, field['wall_height'] + .5])
    lower_index = np.floor(lower_world / resolution).astype(int)
    upper_index = np.floor(upper_world / resolution).astype(int)
    shape = upper_index - lower_index + 1
    occupied = np.zeros(tuple(shape), dtype=bool)
    def mark(triangles):
        lo = np.maximum(np.floor(triangles.min(axis=1) / resolution).astype(int), lower_index)
        hi = np.minimum(np.floor(triangles.max(axis=1) / resolution).astype(int), upper_index)
        for dx in range(3):
            for dy in range(3):
                for dz in range(3):
                    index = lo + [dx, dy, dz]
                    valid = np.all(index <= hi, axis=1)
                    cell = index[valid] - lower_index
                    if len(cell):
                        occupied[cell[:, 0], cell[:, 1], cell[:, 2]] = True
    for instance in instances:
        pending = instance['vertices'][instance['faces']]
        lo, hi = pending.min(axis=1), pending.max(axis=1)
        keep = (hi[:, 2] >= .03) & (lo[:, 2] <= upper_world[2])
        keep &= np.all(lo[:, :2] <= upper_world[:2], axis=1) & np.all(hi[:, :2] >= lower_world[:2], axis=1)
        pending = pending[keep]
        while len(pending):
            small = np.max(np.ptp(pending, axis=1), axis=1) <= resolution * 1.8
            if small.any():
                mark(pending[small])
            large = pending[~small]
            if not len(large):
                break
            a, b, c = large[:, 0], large[:, 1], large[:, 2]
            ab, bc, ca = (a + b) / 2, (b + c) / 2, (c + a) / 2
            pending = np.concatenate((np.stack((a, ab, ca), axis=1), np.stack((ab, b, bc), axis=1),
                                      np.stack((ca, bc, c), axis=1), np.stack((ab, bc, ca), axis=1)))
    # Merge only fully occupied rectangular runs. This cannot fill an empty cell.
    boxes = []
    for start in np.argwhere(occupied):
        ix, iy, iz = map(int, start)
        if not occupied[ix, iy, iz]:
            continue
        ex = ix + 1
        while ex < shape[0] and occupied[ex, iy, iz]:
            ex += 1
        ey = iy + 1
        while ey < shape[1] and occupied[ix:ex, ey, iz].all():
            ey += 1
        ez = iz + 1
        while ez < shape[2] and occupied[ix:ex, iy:ey, ez].all():
            ez += 1
        occupied[ix:ex, iy:ey, iz:ez] = False
        x0, y0, z0 = start + lower_index
        x1, y1, z1 = np.array([ex, ey, ez]) + lower_index
        center = (np.array([x0 + x1, y0 + y1, z0 + z1]) * resolution / 2).tolist()
        size = (np.array([x1 - x0, y1 - y0, z1 - z0]) * resolution).tolist()
        prefix = 'cad'
        for region in layout.get('semantic_regions', []):
            if np.all(np.abs(np.asarray(center) - region['center']) <= np.asarray(region['size']) / 2):
                prefix = region['name']
                break
        boxes.append(dict(name=f'{prefix}_{len(boxes)}', center=center, size=size))
    return boxes


def terrain_triangles(instances, layout):
    """Keep upward CAD surfaces for ToF height queries, independently of voxels."""
    result = []
    ceiling = layout['field']['wall_height'] + .5
    for instance in instances:
        triangles = instance['vertices'][instance['faces']]
        normal = np.cross(triangles[:, 1] - triangles[:, 0], triangles[:, 2] - triangles[:, 0])
        area2 = np.linalg.norm(normal, axis=1)
        keep = (area2 > .0002) & (normal[:, 2] > .02 * area2)
        keep &= (triangles[:, :, 2].min(axis=1) < ceiling) & (triangles[:, :, 2].max(axis=1) >= -.01)
        result.extend(TerrainRow(row) for row in np.round(triangles[keep], 6).tolist())
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--field-step', type=Path, required=True)
    parser.add_argument('--energy-step', type=Path, required=True)
    parser.add_argument('--cache-dir', type=Path, required=True)
    parser.add_argument('--layout', type=Path, default=Path(PKG) / 'config' / 'official_layout.yaml')
    args = parser.parse_args()
    layout = yaml.safe_load(args.layout.read_text())
    if sha256(args.field_step) != layout['source_sha256']:
        raise ValueError('CAD/layout fingerprints differ; re-audit anchors before generating')
    field_cache = args.cache_dir / 'field'
    metadata = read_cache(args.field_step, field_cache)
    energy = read_cache(args.energy_step, args.cache_dir / 'energy')
    if metadata['source_sha256'] != layout['source_sha256']:
        raise ValueError('CAD/layout fingerprints differ; re-audit anchors before generating')
    energy_asset(energy, args.cache_dir / 'energy')
    transform = np.asarray(layout['cad_to_map'], dtype=float)
    targets, armor_models = armor_data(layout, transform)
    model_dir = Path(PKG) / 'models' / 'rmuc2027_official'
    model_dir.mkdir(parents=True, exist_ok=True)
    instances = geometry_assets(metadata, field_cache, model_dir, transform, layout.get('team_instances'))
    geometry = dict(field=layout['field'], obstacles=surface_obstacles(instances, layout),
                    terrain_triangles=terrain_triangles(instances, layout),
                    nofly=layout['nofly'], hangars=layout['hangars'], targets=targets,
                    navigation=layout.get('navigation', {}),
                    vision=layout.get('vision', {}),
                    armor_classes={v: f'{team}_{kind}' for (team, kind), v in ARMOR_CLASSES.items()},
                    scene_objects=layout.get('scene_objects', []),
                    source=dict(cad_sha256=metadata['source_sha256'], map_resolution=layout.get('collision_map_resolution', .15)))
    (Path(PKG) / 'config' / 'field_map_official.yaml').write_text(
        yaml.dump(geometry, Dumper=MapDumper, sort_keys=False, width=150))
    units = ''.join('<include><uri>model://rmuc2027_energy_unit</uri>'
                    f'<name>energy_unit_{index}</name>{pose(*item["pose"])}<static>true</static></include>'
                    for index, item in enumerate(layout.get('energy_units', [])))
    world = ('<?xml version="1.0"?><sdf version="1.6"><world name="rmuc2027_official">'
             '<physics name="default" type="ode"><max_step_size>0.002</max_step_size>'
             '<real_time_update_rate>500</real_time_update_rate></physics><gravity>0 0 -9.81</gravity>'
             '<scene><ambient>0.5 0.5 0.5 1</ambient><background>0.15 0.15 0.18 1</background>'
             '<shadows>false</shadows><grid>false</grid></scene>'
             '<light name="sun" type="directional"><pose>0 0 20 0 0 0</pose>'
             '<diffuse>0.55 0.55 0.55 1</diffuse><direction>-0.3 0.2 -1</direction></light>'
             '<include><uri>model://rmuc2027_official</uri></include>' + ''.join(armor_models) + units +
             '<gui fullscreen="0"><camera name="user_camera"><pose>-16 -12 12 0 .55 .65</pose>'
             '</camera></gui></world></sdf>')
    world_path = Path(PKG) / 'worlds' / 'rmuc2027_official.world'
    world_path.write_text(world)
    runtime = {key: geometry[key] for key in ['field', 'hangars', 'navigation', 'vision']}
    runtime['world_sha256'] = sha256(world_path)
    runtime['field_map_sha256'] = sha256(Path(PKG) / 'config' / 'field_map_official.yaml')
    runtime['cad_sha256'] = metadata['source_sha256']
    (Path(PKG) / 'config' / 'field_runtime_official.yaml').write_text(yaml.safe_dump(runtime, sort_keys=False))
    print(f'Generated {len(targets)} audited armor modules, {len(geometry["obstacles"])} CAD collision boxes')


if __name__ == '__main__':
    main()
